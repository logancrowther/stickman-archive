// Uniform reduction applied to every type's chance except #1000, which stays
// exactly as rare as it has always been.
const RARITY_SCALE = 0.7;

// #1000, The Archive Itself, untouched by RARITY_SCALE — the one number
// nothing else is ever allowed to be rarer than.
const RARITY_1000_FIXED = 1e-23;

// ids 151-999 sit on one continuous geometric curve from TAIL_START_R (just
// under the scaled #150) down to TAIL_END_R (just above #1000's fixed
// rarity), so every id in between is strictly rarer than the id before it.
const TAIL_START_ID = 151;
const TAIL_END_ID = 999;
const TAIL_START_R = 0.000009 * RARITY_SCALE;      // just under scaled #150
const TAIL_END_R = RARITY_1000_FIXED * 50;         // clearly above #1000, never equal to it

// Applied to every type's chance except Circle (#1) and The Archive Itself
// (#1000), both pinned exactly and never touched. Rarity values are tiny
// fractions of a percent, so an exponent < 1 pulls them all a bit closer to
// "common" — mildly near Circle, much more so in the deep tail — while a
// power function preserves the strict decreasing order between ids.
const EASE_EXPONENT = 0.94;

function rawRarityOf(id) {
  // #2-3 are pinned to exact requested values (not run through RARITY_SCALE):
  // Square 2%, Triangle sits at the geometric midpoint between Square and
  // the (scaled) #4 so the drop-off there is even, rather than the old
  // near-tie between #3 and #4.
  if (id <= 3) return RARITY_1_150[id - 1];
  if (id <= 150) return RARITY_1_150[id - 1] * RARITY_SCALE;
  const t = (id - TAIL_START_ID) / (TAIL_END_ID - TAIL_START_ID);
  return TAIL_START_R * Math.pow(TAIL_END_R / TAIL_START_R, t);
}

function rarityOf(id) {
  if (id === 1000) return RARITY_1000_FIXED;
  if (id === 1) return RARITY_1_150[0]; // Circle, pinned exactly
  return 100 * Math.pow(rawRarityOf(id) / 100, EASE_EXPONENT);
}

// Display a rarity percentage at 3 significant figures (leading zeros don't
// count, trailing zeros past the 3rd significant digit are dropped), always
// as a plain decimal — never scientific notation, no matter how tiny.
function formatRarity(p) {
  let exp = Math.floor(Math.log10(p));
  let mantissa = p / Math.pow(10, exp);
  // Guard against toPrecision rounding a mantissa like 9.996 up to "10.0".
  if (parseFloat(mantissa.toPrecision(3)) >= 10) { mantissa /= 10; exp += 1; }
  const digits = mantissa.toPrecision(3).replace(".", "").replace(/0+$/, "");
  if (exp >= digits.length - 1) {
    return digits + "0".repeat(exp - (digits.length - 1)) + "%";
  } else if (exp >= 0) {
    return digits.slice(0, exp + 1) + "." + digits.slice(exp + 1) + "%";
  }
  return "0." + "0".repeat(-exp - 1) + digits + "%";
}

// Money value of a photo of this type (grows with rarity; ids break ties).
function valueOf(type) {
  const f = type.r / 100; // probability as a fraction
  const r = -Math.log10(f);
  const base = Math.max(1, Math.round(Math.pow(10, 0.55 * r)));
  return Math.max(1, Math.round(base * (1 + (type.id - 1) * 0.002)));
}

function formatMoney(n) {
  const suf = ["", "K", "M", "B", "T", "Qa", "Qi", "Sx"];
  let i = 0;
  while (n >= 1000 && i < suf.length - 1) { n /= 1000; i++; }
  const s = n >= 100 || i === 0 ? Math.round(n).toString() : n.toFixed(1).replace(/\.0$/, "");
  return "$" + s + suf[i];
}

function buildTypes() {
  if (NAMES.length !== 1000) {
    console.error(`Stickman Archive: expected exactly 1000 types, found ${NAMES.length}`);
  }
  return NAMES.map((nd, i) => {
    const t = { id: i + 1, name: nd[0], desc: nd[1], r: rarityOf(i + 1) };
    t.value = valueOf(t);
    return t;
  });
}

